const ALL_NAMES = [...MALE_NAMES, ...FEMALE_NAMES, ...SURNAMES];

// normalizeGreek(word) -> σωστά τονισμένη μορφή
const KNOWN_NAMES = new Map(ALL_NAMES.map((name) => [normalizeGreek(name), name]));

// Κεφαλαίο μόνο το πρώτο γράμμα, τα υπόλοιπα πεζά, τελικό "σ" -> "ς".
// Χρησιμοποιείται όταν η λέξη δεν βρέθηκε στη λίστα γνωστών ονομάτων.
function fixCaseOnly(word) {
  if (!word) return word;
  let w = word.toLowerCase();
  if (w.endsWith("σ")) w = w.slice(0, -1) + "ς";
  return w.charAt(0).toUpperCase() + w.slice(1);
}

function fixWord(word) {
  if (!word) return word;
  const known = KNOWN_NAMES.get(normalizeGreek(word));
  return known || fixCaseOnly(word);
}

// Μορφοποιεί ένα πλήρες όνομα για εμφάνιση, λέξη-λέξη (και ανά παύλα μέσα
// σε σύνθετες λέξεις, π.χ. "παπα-δημητριου" -> "Παπα-Δημητρίου").
// π.χ. "γιωργος παπαδοπουλος" -> "Γιώργος Παπαδόπουλος"
export function toDisplayName(input) {
  if (!input) return input;

  return String(input)
    .trim()
    .replace(/\s+/g, " ")
    .split(" ")
    .map((word) => word.split("-").map(fixWord).join("-"))
    .join(" ");
}
