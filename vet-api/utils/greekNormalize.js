// utils/greekNormalize.js
//
// Κανονικοποίηση ελληνικού κειμένου για ανεκτική αναζήτηση:
// - Αφαιρεί τόνους/διαλυτικά (πέρλα -> περλα)
// - Ενοποιεί ομόηχα φωνήεντα/διφθόγγους που μπερδεύονται συχνά στην ορθογραφία
//   (παιρλα -> περλα, αφού το "αι" προφέρεται σαν "ε")
// - Πεζά, χωρίς περιττά κενά
//
// Χρησιμοποιείται και στο ίδιο string (name -> nameNormalized) και στο query
// του χρήστη, ώστε η σύγκριση να γίνεται πάντα σε "ουδέτερη" μορφή.
export function normalizeGreek(input) {
  if (!input) return "";

  let s = String(input)
    .toLowerCase()
    .normalize("NFD")
    .replace(/[̀-ͯ]/g, ""); // αφαίρεση τόνων/διαλυτικών

  // Δίφθογγοι πρώτα (πριν τα μεμονωμένα φωνήεντα, αλλιώς θα ξαναγραφούν)
  s = s
    .replace(/αι/g, "ε")
    .replace(/ει/g, "ι")
    .replace(/οι/g, "ι")
    .replace(/υι/g, "ι")
    .replace(/η/g, "ι")
    .replace(/υ/g, "ι")
    .replace(/ω/g, "ο")
    .replace(/ς/g, "σ");

  return s.trim().replace(/\s+/g, " ");
}

// Κεφαλαία χωρίς τόνους/διαλυτικά — για SMS: το GSM-7 alphabet (160
// χαρακτήρες/SMS) καλύπτει τα ελληνικά ΚΕΦΑΛΑΙΑ χωρίς τόνο, ενώ οποιοδήποτε
// πεζό ή τονισμένο γράμμα αναγκάζει το δίκτυο σε UCS-2 (μόλις 70
// χαρακτήρες/SMS) — άρα λιγότερα, φθηνότερα segments.
// Σε αντίθεση με το normalizeGreek(), ΔΕΝ ενοποιεί ομόηχα — κρατάει το
// κείμενο αναγνώσιμο, μόνο αφαιρεί τόνους και κάνει κεφαλαία.
export function toUpperNoAccents(input) {
  if (!input) return "";
  return String(input)
    .normalize("NFD")
    .replace(/[̀-ͯ]/g, "")
    .toUpperCase();
}
